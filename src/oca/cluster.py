"""Serve a model with vLLM in a UCloud job and reach it through an SSH tunnel.

Remote layout on the configured drive (``cluster_drive``):

    <drive>/hf/<org>/<repo>/   weights in Hugging Face layout, shared by every job
    <drive>/oca/               job scripts, logs, caches and the vLLM venv

Jobs run the ``terminal-almalinux`` app (it accepts SSH) as batch jobs: the job ends when
its script exits, and the serve script exits after ``cluster_idle`` minutes without
requests, so a forgotten session stops spending GPU-hours on its own.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import signal
import socket
import subprocess
import time
from collections.abc import Callable, Iterator
from contextlib import contextmanager, suppress
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

import httpx

from .config import VLLM_VERSION, ClusterModel, OcaError, Settings, data_dir

if TYPE_CHECKING:  # ucloud_api is imported lazily: it is slow and only needed here
    from ucloud_api import UCloudClient
    from ucloud_api.models import JobSpecification

APP = ("terminal-almalinux", "Aug2026")
CPU_PRODUCT = "cpu-amd-zen5-2-vcpu"
REMOTE_PORT = 8000
MARKER = ".oca-complete"  # written once a download finished
HF_CLI = "huggingface_hub[hf_xet]>=0.34"


@dataclass
class Job:
    kind: str  # "serve" or "pull"
    job_id: str
    model: str
    tag: str
    tunnel_pid: int = 0


# -- local state ---------------------------------------------------------------------------


def state_path() -> Path:
    return data_dir() / "run" / "cluster.json"


def _read_all() -> dict[str, Job]:
    try:
        raw = json.loads(state_path().read_text())
        return {kind: Job(**job) for kind, job in raw.items()}
    except (FileNotFoundError, ValueError, TypeError):
        return {}


def read(kind: str) -> Job | None:
    return _read_all().get(kind)


def _write(job: Job | None, kind: str) -> None:
    jobs = _read_all()
    if job is None:
        jobs.pop(kind, None)
    else:
        jobs[kind] = job
    state_path().parent.mkdir(parents=True, exist_ok=True)
    state_path().write_text(json.dumps({k: asdict(v) for k, v in jobs.items()}))


# -- remote scripts (pure, unit-tested) ----------------------------------------------------


def _model_dir(model: ClusterModel) -> str:
    return f"/work/hf/{model.repo}"


def _download(model: ClusterModel) -> list[str]:
    d = _model_dir(model)
    return [
        f'if [ ! -f "{d}/{MARKER}" ]; then',
        f'  uvx --from "{HF_CLI}" hf download {model.repo} --local-dir "{d}" || exit 1',
        f'  touch "{d}/{MARKER}"',
        "fi",
    ]


def _wrap(tag: str, body: list[str]) -> str:
    """Tee everything to a log on the drive, so failures are readable after the job ends."""
    return "\n".join(
        [
            "#!/usr/bin/env bash",
            "# Generated by oca.",
            "set -uo pipefail",
            "mkdir -p /work/oca/logs",
            "{",
            'export PATH="$HOME/.local/bin:$PATH"',
            "export UV_CACHE_DIR=/work/oca/cache/uv UV_PYTHON_INSTALL_DIR=/work/oca/cache/python",
            "command -v uv >/dev/null || curl -LsSf https://astral.sh/uv/install.sh | sh",
            *body,
            f'}} 2>&1 | tee -a "/work/oca/logs/{tag}.log"',
            'exit "${PIPESTATUS[0]}"',
        ]
    )


def pull_script(model: ClusterModel, tag: str) -> str:
    return _wrap(tag, [*_download(model), f'echo "oca: {model.id} downloaded"'])


def serve_command(model: ClusterModel) -> list[str]:
    return [
        *("/work/oca/venvs/vllm-" + VLLM_VERSION + "/bin/vllm", "serve", _model_dir(model)),
        *("--served-model-name", model.id),
        *("--host", "127.0.0.1", "--port", str(REMOTE_PORT)),
        *("--max-model-len", str(model.context)),
        *model.args,
    ]


def serve_script(model: ClusterModel, settings: Settings, tag: str) -> str:
    venv = f"/work/oca/venvs/vllm-{VLLM_VERSION}"
    health = f"http://127.0.0.1:{REMOTE_PORT}"
    env = " ".join(f"{k}={shlex.quote(v)}" for k, v in model.env)
    return _wrap(
        tag,
        [
            "nvidia-smi -L || exit 1",
            *_download(model),
            f'if [ ! -x "{venv}/bin/vllm" ]; then',
            f'  rm -rf "{venv}" && uv venv -p 3.12 "{venv}" || exit 1',
            f'  uv pip install -p "{venv}" "vllm=={VLLM_VERSION}" --torch-backend=auto || exit 1',
            "fi",
            # Compile caches on the drive make every start after the first one faster.
            "export XDG_CACHE_HOME=/work/oca/cache VLLM_CACHE_ROOT=/work/oca/cache/vllm",
            "export HF_HUB_OFFLINE=1",
            *([f"export {env}"] if env else []),
            shlex.join(serve_command(model)) + " &",
            "pid=$!",
            f"until curl -sf {health}/health >/dev/null; do",
            '  kill -0 "$pid" 2>/dev/null || { wait "$pid"; exit "$?"; }',
            "  sleep 10",
            "done",
            'echo "oca: ready"',
            # Stop when the token counters have not moved for cluster_idle minutes.
            'idle=0; last=""; stopped=0',
            'while kill -0 "$pid" 2>/dev/null; do',
            "  sleep 60",
            f"  now=$(curl -sf {health}/metrics | grep -E '^vllm:(num_requests_running|"
            "prompt_tokens_total|generation_tokens_total)')",
            # No metrics is not proof of idleness: leave the stop to the time allocation.
            '  [ -z "$now" ] && continue',
            '  if [ "$now" = "$last" ]; then idle=$((idle + 1)); else idle=0; last="$now"; fi',
            f'  if [ "$idle" -ge {settings.cluster_idle} ] && [ "$stopped" = 0 ]; then',
            f'    echo "oca: idle for {settings.cluster_idle} min, stopping"',
            '    stopped=1; kill "$pid"',
            "  fi",
            "done",
            'wait "$pid"; code=$?',
            '[ "$stopped" = 1 ] && exit 0',
            'exit "$code"',
        ],
    )


# -- UCloud -----------------------------------------------------------------------------


@contextmanager
def _client() -> Iterator[UCloudClient]:
    from ucloud_api import UCloudClient
    from ucloud_api.exceptions import AuthError, ConfigError

    try:
        with UCloudClient() as client:
            yield client
    except (AuthError, ConfigError) as e:
        raise OcaError(f"{e}\nLog in with `oca ucloud login`.") from e


def _drive(settings: Settings) -> str:
    if not settings.cluster_drive:
        raise OcaError(
            "no UCloud drive configured. List drives with `oca ucloud files drives`, then "
            "e.g. `oca config cluster_drive /12383018`"
        )
    return settings.cluster_drive.rstrip("/")


def _spec(settings: Settings, name: str, script: str, gpus: int, hours: int) -> JobSpecification:
    from ucloud_api import ComputeProduct, JobSpecification, NameAndVersion, SimpleDuration
    from ucloud_api.models import FileParam

    drive = _drive(settings)
    if gpus:
        product = ComputeProduct(
            id=f"gpu-nvidia-b200-{gpus}-gpu", category="gpu-nvidia-b200", provider="ucloud"
        )
    else:
        product = ComputeProduct(id=CPU_PRODUCT, category="cpu-amd-zen5", provider="ucloud")
    return JobSpecification(
        application=NameAndVersion(name=APP[0], version=APP[1]),
        product=product,
        name=name,
        parameters={"batchScript": FileParam(path=script, read_only=True)},
        resources=[FileParam(path=f"{drive}/hf"), FileParam(path=f"{drive}/oca")],
        time_allocation=SimpleDuration(hours=hours),
        ssh_enabled=True if gpus else None,
    )


PULL_HOURS = 8  # a 510 GB download fits; an unfinished one resumes on the next pull


def _submit(settings: Settings, job: Job, script: str, gpus: int) -> Job:
    from ucloud_api import Files, Jobs, Transfer
    from ucloud_api.exceptions import APIError

    drive = _drive(settings)
    with _client() as client:
        files = Files(client)
        for folder in ("hf", "oca", "oca/jobs", "oca/logs"):
            if files.stat(f"{drive}/{folder}") is None:
                with suppress(APIError):
                    files.mkdir(f"{drive}/{folder}", conflict_policy="REJECT")
        local = data_dir() / "run" / f"{job.tag}.sh"
        local.parent.mkdir(parents=True, exist_ok=True)
        local.write_text(script)
        remote = f"{drive}/oca/jobs/{job.tag}.sh"
        Transfer(client).upload(local, remote)
        hours = settings.cluster_hours if gpus else PULL_HOURS
        job.job_id = Jobs(client).create(
            _spec(settings, re.sub(r"[^A-Za-z0-9-]", "-", f"oca-{job.tag}"), remote, gpus, hours)
        )
    _write(job, job.kind)
    return job


def _new(kind: str, model: ClusterModel) -> Job:
    return Job(kind, "", model.id, f"{kind}-{model.id}-{time.strftime('%Y%m%d-%H%M%S')}")


def weights_ready(settings: Settings, model: ClusterModel) -> bool:
    from ucloud_api import Files

    with _client() as client:
        return Files(client).stat(f"{_drive(settings)}/hf/{model.repo}/{MARKER}") is not None


def pull(settings: Settings, model: ClusterModel) -> Job:
    """Download weights to the drive from a cheap CPU job."""
    job = _new("pull", model)
    return _submit(settings, job, pull_script(model, job.tag), gpus=0)


def submit_serve(settings: Settings, model: ClusterModel) -> Job:
    job = _new("serve", model)
    return _submit(settings, job, serve_script(model, settings, job.tag), model.gpus)


def job_status(job: Job) -> dict[str, Any]:
    from ucloud_api import Jobs

    with _client() as client:
        status = Jobs(client).retrieve(job.job_id, include_updates=False).get("status", {})
    return status if isinstance(status, dict) else {}


def log_text(settings: Settings, job: Job) -> str:
    """The job script's log, read from the drive (works after the job ended too)."""
    from ucloud_api import Transfer
    from ucloud_api.exceptions import UCloudError

    try:
        with _client() as client:
            data: bytes = Transfer(client).read_bytes(f"{_drive(settings)}/oca/logs/{job.tag}.log")
    except UCloudError:
        return ""
    return data.decode(errors="replace")


def log_tail(settings: Settings, job: Job, lines: int = 40) -> str:
    return "\n".join(log_text(settings, job).splitlines()[-lines:])


def extend(job: Job, hours: int) -> None:
    from ucloud_api import Jobs

    with _client() as client:
        Jobs(client).extend(job.job_id, hours=hours)


def terminate(kind: str) -> bool:
    """Stop a job and its tunnel; forget it. Returns False when there was none."""
    from ucloud_api import Jobs
    from ucloud_api.exceptions import APIError

    job = read(kind)
    if job is None:
        return False
    stop_tunnel(job)
    with _client() as client, suppress(APIError):  # already finished is fine
        Jobs(client).terminate(job.job_id)
    _write(None, kind)
    return True


# -- tunnel ---------------------------------------------------------------------------------


def tunnel_command(
    user: str, host: str, port: int, local_port: int, known_hosts: Path
) -> list[str]:
    return [
        *("ssh", "-N", "-p", str(port)),
        *("-L", f"127.0.0.1:{local_port}:127.0.0.1:{REMOTE_PORT}"),
        *("-o", "BatchMode=yes", "-o", "ExitOnForwardFailure=yes"),
        *("-o", "ServerAliveInterval=30", "-o", "ServerAliveCountMax=3"),
        # Each job has a fresh host key: trust it on first use, per job.
        *("-o", "StrictHostKeyChecking=accept-new", "-o", f"UserKnownHostsFile={known_hosts}"),
        f"{user}@{host}",
    ]


def _alive(pid: int) -> bool:
    try:
        return pid > 0 and b"ssh" in Path(f"/proc/{pid}/cmdline").read_bytes()
    except OSError:
        return False


def _port_open(port: int) -> bool:
    with socket.socket() as s:
        s.settimeout(1)
        return s.connect_ex(("127.0.0.1", port)) == 0


def ensure_tunnel(settings: Settings, job: Job, timeout: float = 300) -> None:
    from ucloud_api import Jobs

    if _alive(job.tunnel_pid) and _port_open(settings.cluster_port):
        return
    stop_tunnel(job)
    with _client() as client:
        jobs = Jobs(client)
        deadline = time.monotonic() + timeout
        while (endpoint := jobs.ssh_endpoint(job.job_id)) is None:
            if time.monotonic() > deadline:
                raise OcaError(f"job {job.job_id} advertised no SSH endpoint")
            time.sleep(5)
    log = data_dir() / "logs" / "tunnel.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    known = data_dir() / "run" / f"known_hosts-{job.job_id}"
    cmd = tunnel_command(endpoint.user, endpoint.host, endpoint.port, settings.cluster_port, known)
    with log.open("ab") as fh:
        proc = subprocess.Popen(
            cmd,
            stdin=subprocess.DEVNULL,
            stdout=fh,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
    for _ in range(30):
        if proc.poll() is not None:
            raise OcaError(f"SSH tunnel failed; see {log}")
        if _port_open(settings.cluster_port):
            job.tunnel_pid = proc.pid
            _write(job, job.kind)
            return
        time.sleep(1)
    proc.kill()
    raise OcaError(f"SSH tunnel did not open port {settings.cluster_port}; see {log}")


def stop_tunnel(job: Job) -> None:
    if _alive(job.tunnel_pid):
        os.kill(job.tunnel_pid, signal.SIGTERM)


def healthy(settings: Settings) -> bool:
    try:
        url = f"http://127.0.0.1:{settings.cluster_port}/health"
        return httpx.get(url, timeout=5).status_code == 200
    except httpx.HTTPError:
        return False


def check(settings: Settings, job: Job) -> str | None:
    """One connection attempt: None when the server answers, else what it is doing.

    Re-opens the tunnel if needed. A finished job is forgotten and raises.
    """
    from ucloud_api import Jobs, JobState

    with _client() as client:
        state = Jobs(client).state(job.job_id)
    if state.is_terminal:
        _write(None, job.kind)
        tail = log_tail(settings, job)
        raise OcaError(f"job {job.job_id} ended ({state.value}). Log tail:\n{tail}")
    if state != JobState.RUNNING:
        return str(state.value).lower().replace("_", " ")
    ensure_tunnel(settings, job)
    if healthy(settings):
        return None
    last = log_tail(settings, job, lines=1)
    return f"loading: {last[-100:]}" if last else "starting"


def wait_ready(
    settings: Settings, job: Job, on_progress: Callable[[str], None], timeout: float = 7200
) -> None:
    """Block until the remote server answers, reporting the job state and last log line."""
    deadline = time.monotonic() + timeout
    while (doing := check(settings, job)) is not None:
        on_progress(doing)
        if time.monotonic() > deadline:
            raise OcaError(f"not ready after {timeout / 60:.0f} min; see `oca cluster logs`")
        time.sleep(10)
